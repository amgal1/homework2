sales = {
    "Понедельник": [("капучино", 120, 14), ("латте", 150, 9), ("чай", 60, 21)],
    "Вторник":     [("капучино", 120, 8),  ("эспрессо", 90, 17), ("чай", 60, 12)],
    "Среда":       [("латте", 150, 11), ("эспрессо", 90, 6), ("какао", 110, 13)],
    "Четверг":     [("капучино", 120, 16), ("латте", 150, 7), ("чай", 60, 18)],
    "Пятница":     [("капучино", 120, 10), ("эспрессо", 90, 21), ("какао", 110, 9)],
}

g = {"Понедельник": "Понедельника", "Вторник": "Вторника", "Среда": "Среды",
     "Четверг": "Четверга", "Пятница": "Пятницы"}


def total(a):
    s = 0
    for n, p, q in a:
        s += p * q
    return s


def hit(a):
    b = ""
    m = 0
    for n, p, q in a:
        if q > m:
            m = q
            b = n
    return b


def show(d, a):
    print(d + ": выручка", total(a))
    print("Хит " + g.get(d, d) + ":", hit(a))


for d in sales:
    show(d, sales[d])
